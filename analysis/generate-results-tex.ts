/**
 * Write sections/generated-result-values.tex from analysis/csv/ exports.
 *
 * Usage: cd analysis && bun run gen-tex
 */

import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { computeStudyStats } from "./lib/stats.ts";

const ANALYSIS_DIR = dirname(new URL(import.meta.url).pathname);
const CSV_DIR = join(ANALYSIS_DIR, "csv");
const OUT_TEX = join(ANALYSIS_DIR, "../sections/generated-result-values.tex");

function escapeLaTeX(s: string): string {
  return s
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/&/g, "\\&")
    .replace(/%/g, "\\%")
    .replace(/#/g, "\\#")
    .replace(/_/g, "\\_");
}

function fmtP(p: number | null): string {
  if (p === null) return "---";
  if (p < 0.0005) return "\\textless 0.001";
  return p.toFixed(3);
}

/** Full clause after “A Wilcoxon signed-rank test …” */
function wilcoxonResultClause(p: number | null, n: number): string {
  if (n === 0 || p === null) {
    return "could not be computed because there were no non-zero paired differences";
  }
  return p < 0.05
    ? "yielded a statistically significant difference"
    : "did not yield a statistically significant difference";
}

function safeFixed(x: number | undefined, d: number): string {
  if (x === undefined || !Number.isFinite(x)) return "---";
  return x.toFixed(d);
}

function cmd(lines: string[], name: string, body: string): void {
  lines.push(`\\providecommand{\\${name}}{${body}}`);
}

function main(): void {
  if (!existsSync(join(CSV_DIR, "paired_time.csv"))) {
    console.error("Missing CSVs. Run `bun run export`, then `bun run gen-tex`.");
    process.exit(1);
  }

  const s = computeStudyStats(CSV_DIR);
  const v = s.overview.validN;
  const pct = (a: number, b: number) =>
    b > 0 ? Math.round((100 * a) / b).toString() : "---";

  const lines: string[] = [
    "% AUTO-GENERATED by analysis/generate-results-tex.ts — do not edit by hand.",
    "% Regenerate: cd analysis && bun run gen-tex",
    "",
  ];

  cmd(lines, "GenNTotal", String(s.overview.totalAccessed));
  cmd(lines, "GenNValid", String(v));
  cmd(lines, "GenDemoAge", escapeLaTeX(s.demographics.ageSummary));
  cmd(lines, "GenDemoWebMdn", safeFixed(s.demographics.webMdn, 1));
  cmd(lines, "GenDemoWebIqr", s.demographics.webIqr);
  cmd(lines, "GenDemoAiMdn", safeFixed(s.demographics.aiMdn, 1));
  cmd(lines, "GenDemoAiIqr", s.demographics.aiIqr);
  cmd(lines, "GenCounterBaselineFirstN", String(s.demographics.baselineFirstN));
  cmd(lines, "GenCounterBaselineFirstPct", pct(s.demographics.baselineFirstN, v));
  cmd(lines, "GenCounterEphemeralFirstN", String(s.demographics.ephemeralFirstN));
  cmd(lines, "GenCounterEphemeralFirstPct", pct(s.demographics.ephemeralFirstN, v));

  cmd(lines, "GenCompNBaseline", String(s.completion.nBaselineCorrect));
  cmd(lines, "GenCompNEphemeral", String(s.completion.nEphemeralCorrect));
  cmd(lines, "GenCompPctBaseline", s.completion.pctBaseline.toFixed(1));
  cmd(lines, "GenCompPctEphemeral", s.completion.pctEphemeral.toFixed(1));
  cmd(lines, "GenCompMcNemarP", fmtP(s.completion.mcnemarP));

  const tw = s.time.wilcoxon;
  cmd(lines, "GenTimeBaselineMdn", safeFixed(s.time.baselineMdn, 1));
  cmd(lines, "GenTimeBaselineIqr", s.time.baselineIqr);
  cmd(lines, "GenTimeEphemeralMdn", safeFixed(s.time.ephemeralMdn, 1));
  cmd(lines, "GenTimeEphemeralIqr", s.time.ephemeralIqr);
  cmd(
    lines,
    "GenTimeWilcoxonResult",
    wilcoxonResultClause(tw?.p ?? null, tw?.n ?? 0),
  );
  cmd(lines, "GenTimeW", tw && tw.n > 0 ? String(Math.round(tw.W)) : "---");
  cmd(lines, "GenTimeP", fmtP(tw?.p ?? null));
  cmd(lines, "GenTimeR", tw && tw.n > 0 ? tw.r.toFixed(3) : "---");

  const iw = s.interactions.wilcoxon;
  cmd(lines, "GenIntBaselineMdn", safeFixed(s.interactions.baselineMdn, 1));
  cmd(lines, "GenIntBaselineIqr", s.interactions.baselineIqr);
  cmd(lines, "GenIntEphemeralMdn", safeFixed(s.interactions.ephemeralMdn, 1));
  cmd(lines, "GenIntEphemeralIqr", s.interactions.ephemeralIqr);
  cmd(
    lines,
    "GenIntWilcoxonResult",
    wilcoxonResultClause(iw?.p ?? null, iw?.n ?? 0),
  );
  cmd(lines, "GenIntW", iw && iw.n > 0 ? String(Math.round(iw.W)) : "---");
  cmd(lines, "GenIntP", fmtP(iw?.p ?? null));
  cmd(lines, "GenIntR", iw && iw.n > 0 ? iw.r.toFixed(3) : "---");

  const lk = [
    ["helpfulness", "Helpfulness"],
    ["intrusiveness", "Intrusiveness"],
    ["control", "Control"],
  ] as const;
  for (const [key, cap] of lk) {
    const L = s.likert[key];
    const w = L?.wilcoxon;
    cmd(lines, `GenLikert${cap}BaselineMdn`, L ? safeFixed(L.baselineMdn, 1) : "---");
    cmd(lines, `GenLikert${cap}BaselineIqr`, L ? L.baselineIqr : "---");
    cmd(lines, `GenLikert${cap}EphemeralMdn`, L ? safeFixed(L.ephemeralMdn, 1) : "---");
    cmd(lines, `GenLikert${cap}EphemeralIqr`, L ? L.ephemeralIqr : "---");
    cmd(lines, `GenLikert${cap}P`, fmtP(w?.p ?? null));
  }

  const pPref = s.preference.final_preference;
  cmd(lines, "GenPrefOverallB", String(pPref?.baseline ?? 0));
  cmd(lines, "GenPrefOverallE", String(pPref?.ephemeral ?? 0));
  cmd(lines, "GenPrefOverallN", String(pPref?.noPreference ?? 0));
  cmd(lines, "GenPrefHelpB", String(s.preference.final_helpfulness?.baseline ?? 0));
  cmd(lines, "GenPrefHelpE", String(s.preference.final_helpfulness?.ephemeral ?? 0));
  cmd(lines, "GenPrefHelpN", String(s.preference.final_helpfulness?.noPreference ?? 0));
  cmd(lines, "GenPrefIntrB", String(s.preference.final_intrusiveness?.baseline ?? 0));
  cmd(lines, "GenPrefIntrE", String(s.preference.final_intrusiveness?.ephemeral ?? 0));
  cmd(lines, "GenPrefIntrN", String(s.preference.final_intrusiveness?.noPreference ?? 0));
  cmd(lines, "GenPrefLifeB", String(s.preference.final_real_life?.baseline ?? 0));
  cmd(lines, "GenPrefLifeE", String(s.preference.final_real_life?.ephemeral ?? 0));
  cmd(lines, "GenPrefLifeN", String(s.preference.final_real_life?.noPreference ?? 0));
  cmd(lines, "GenPrefOverallBinomialP", fmtP(pPref?.binomialP ?? null));

  cmd(lines, "GenEngNTriggered", String(s.engagement.nTriggeredOrRequested));
  cmd(lines, "GenEngPctTriggered", s.engagement.pctTriggered.toFixed(1));
  cmd(lines, "GenEngNUsed", String(s.engagement.nUsed));
  cmd(lines, "GenEngNDismissed", String(s.engagement.nDismissed));
  cmd(lines, "GenEngNIgnored", String(s.engagement.nIgnored));
  cmd(lines, "GenEngNExpanded", String(s.engagement.nExpanded));
  cmd(lines, "GenEngTotalGen", String(s.engagement.totalGenerations));
  cmd(lines, "GenEngFallbackCount", String(s.engagement.fallbackCount));
  cmd(lines, "GenEngFallbackPct", s.engagement.fallbackPct.toFixed(1));

  cmd(lines, "GenSumCompPctB", s.summary.completionPctBaseline.toFixed(1));
  cmd(lines, "GenSumCompPctE", s.summary.completionPctEphemeral.toFixed(1));
  cmd(lines, "GenSumMcNemarP", fmtP(s.summary.mcnemarP));
  cmd(lines, "GenSumTimeBMdn", safeFixed(s.time.baselineMdn, 1));
  cmd(lines, "GenSumTimeEMdn", safeFixed(s.time.ephemeralMdn, 1));
  cmd(lines, "GenSumTimeP", fmtP(tw?.p ?? null));
  cmd(lines, "GenSumIntBMdn", safeFixed(s.interactions.baselineMdn, 1));
  cmd(lines, "GenSumIntEMdn", safeFixed(s.interactions.ephemeralMdn, 1));
  cmd(lines, "GenSumIntP", fmtP(iw?.p ?? null));
  cmd(lines, "GenSumHelpBMdn", safeFixed(s.likert.helpfulness?.baselineMdn, 1));
  cmd(lines, "GenSumHelpEMdn", safeFixed(s.likert.helpfulness?.ephemeralMdn, 1));
  cmd(lines, "GenSumHelpP", fmtP(s.likert.helpfulness?.wilcoxon?.p ?? null));
  cmd(lines, "GenSumIntrBMdn", safeFixed(s.likert.intrusiveness?.baselineMdn, 1));
  cmd(lines, "GenSumIntrEMdn", safeFixed(s.likert.intrusiveness?.ephemeralMdn, 1));
  cmd(lines, "GenSumIntrP", fmtP(s.likert.intrusiveness?.wilcoxon?.p ?? null));
  cmd(lines, "GenSumCtrlBMdn", safeFixed(s.likert.control?.baselineMdn, 1));
  cmd(lines, "GenSumCtrlEMdn", safeFixed(s.likert.control?.ephemeralMdn, 1));
  cmd(lines, "GenSumCtrlP", fmtP(s.likert.control?.wilcoxon?.p ?? null));
  cmd(
    lines,
    "GenSumPrefOverall",
    `${pPref?.baseline ?? 0} chose baseline; ${pPref?.ephemeral ?? 0} chose ephemeral; ${pPref?.noPreference ?? 0} no preference`,
  );
  cmd(lines, "GenSumPrefOverallP", fmtP(pPref?.binomialP ?? null));

  lines.push("");
  mkdirSync(dirname(OUT_TEX), { recursive: true });
  writeFileSync(OUT_TEX, lines.join("\n") + "\n", "utf-8");
  console.log(`Wrote ${OUT_TEX}`);
}

main();
